#!/usr/bin/env bash
# Build a WordPress.org-ready release zip (respects .distignore).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SLUG="beepbeep-titles"
VERSION="$(grep "define( 'BEEPTI_VERSION'" "$ROOT/beepbeep-titles.php" | sed -E "s/.*'([0-9.]+)'.*/\1/")"
DIST="$ROOT/dist"
STAGE="$DIST/$SLUG"
ZIP="$DIST/${SLUG}-${VERSION}.zip"

cd "$ROOT"

if [[ ! -d build ]]; then
	echo "Missing build/ — run: npm run build" >&2
	exit 1
fi

if [[ ! -f readme.txt ]]; then
	echo "Missing readme.txt" >&2
	exit 1
fi

mkdir -p "$DIST"
rm -rf "$STAGE"
mkdir -p "$STAGE"

# Copy everything except .distignore patterns (and the dist folder itself).
while IFS= read -r line || [[ -n "$line" ]]; do
	line="${line%%#*}"
	line="$(echo "$line" | xargs)"
	[[ -z "$line" ]] && continue
	EXCLUDES+=( "--exclude=$line" )
done < "$ROOT/.distignore"

# Stage from the committed tree (git archive HEAD), not the working copy, so
# untracked notes (HANDOVER.md, briefs) and a worktree's .git file cannot ship.
# build/ is generated by npm run build and is not committed, so it is copied in
# from the working tree. BUILD_FROM_WORKTREE=1 stages the working copy (debug only).
SRC="$ROOT"
SRC_TMP=""
if [[ "${BUILD_FROM_WORKTREE:-0}" != "1" ]]; then
	if [[ -n "$(git -C "$ROOT" status --porcelain --untracked-files=no)" ]]; then
		echo "WARNING: uncommitted changes are NOT in this zip (built from $(git -C "$ROOT" rev-parse --short HEAD))." >&2
	fi
	SRC_TMP="$(mktemp -d)"
	trap 'rm -rf "$SRC_TMP"' EXIT
	SRC="$SRC_TMP/src"
	mkdir -p "$SRC"
	git -C "$ROOT" archive --format=tar HEAD | tar -x -C "$SRC"
	rm -rf "$SRC/build"
	cp -a "$ROOT/build" "$SRC/build"
fi

rsync -a "${EXCLUDES[@]}" --exclude='dist' --exclude='.git' --exclude='HANDOVER*.md' --exclude='AGENTS.md' \
	--exclude='*BRIEF*.md' --exclude='*brief*.md' "$SRC/" "$STAGE/"

if find "$STAGE" -type f \( -name 'screenshot-*.png' -o -name '.DS_Store' -o -name '.env' -o -name '.env.*' \) -print -quit | grep -q .; then
	echo "Release staging contains a forbidden file" >&2
	exit 1
fi

rm -f "$ZIP"
(
	cd "$DIST"
	zip -r -q "$(basename "$ZIP")" "$SLUG"
)

# Guard: never ship git metadata, internal notes or dev files.
if unzip -Z1 "$ZIP" | grep -Ei '(^|/)\.git(/|$)|(^|/)HANDOVER[^/]*\.md$|(^|/)AGENTS\.md$|brief[^/]*\.md$|(^|/)\.(claude|cursor)(/|$)|(^|/)node_modules/|(^|/)tests/'; then
	echo "ERROR: $ZIP contains git metadata, internal notes or dev files (listed above)" >&2
	rm -f "$ZIP"
	exit 1
fi

echo "Release zip: $ZIP"
echo "Version:     $VERSION"
du -h "$ZIP"
